export const SUPPORTED_UI_LOCALES = [
  "en",
  "zh-CN",
  "zh-TW",
  "ja",
  "ko",
  "es",
  "fr",
  "de",
  "pt-BR",
  "ru",
] as const;

export type UiLocale = (typeof SUPPORTED_UI_LOCALES)[number];

const dictionaries: Record<UiLocale, Record<MessageKey, string>> = {
  en,
  "zh-CN": zh,
  "zh-TW": zhTwMessages,
  ja: jaMessages,
  ko: koMessages,
  es: esMessages,
  fr: frMessages,
  de: deMessages,
  "pt-BR": ptBrMessages,
  ru: ruMessages,
};

export function resolveUiLocale(locale: string): UiLocale {
  const normalized = locale.trim().replaceAll("_", "-").toLowerCase();
  if (normalized.startsWith("zh")) {
    return /^zh-(tw|hk|mo|hant)/.test(normalized) ? "zh-TW" : "zh-CN";
  }
  if (normalized.startsWith("ja")) {
    return "ja";
  }
  if (normalized.startsWith("ko")) {
    return "ko";
  }
  if (normalized.startsWith("es")) {
    return "es";
  }
  if (normalized.startsWith("fr")) {
    return "fr";
  }
  if (normalized.startsWith("de")) {
    return "de";
  }
  if (normalized.startsWith("pt")) {
    return "pt-BR";
  }
  if (normalized.startsWith("ru")) {
    return "ru";
  }
  return "en";
}

export function getBrowserLocale(): UiLocale {
  const browserLocale =
    typeof chrome !== "undefined" && chrome.i18n?.getUILanguage
      ? chrome.i18n.getUILanguage()
      : navigator.language;
  return resolveUiLocale(browserLocale);
}

export const uiLocale = getBrowserLocale();

export function translateForLocale(
  locale: string,
  key: MessageKey,
  params: MessageParams = {},
): string {
  const dictionary = dictionaries[resolveUiLocale(locale)];
  return dictionary[key].replace(/\{(\w+)\}/g, (_match, name: string) =>
    String(params[name] ?? `{${name}}`),
  );
}

export function t(key: MessageKey, params: MessageParams = {}): string {
  return translateForLocale(uiLocale, key, params);
}
